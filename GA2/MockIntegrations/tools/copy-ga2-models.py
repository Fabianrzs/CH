"""Copia los DTO REST de GA2 (Dodo, TusDatos) al proyecto mock.

Uso (desde la raíz del repositorio GA2): python3 MockIntegrations/tools/copy-ga2-models.py
"""
import re,os,sys
import pathlib
root=pathlib.Path(__file__).resolve().parents[2]
src=str(root/'src/GA2.Domain/Core/ReferenciasSvc')
dst=str(root/'MockIntegrations/src/MockIntegrations.Api/Providers')
def conv(path, ns, outpath):
    t=open(path,encoding='utf-8-sig').read()
    t=re.sub(r'^using (GA2|Microsoft\.AspNetCore|Newtonsoft)[^\n]*\n','',t,flags=re.M)
    t=re.sub(r'^using System[^\n]*\n','',t,flags=re.M)
    t=re.sub(r'\s*:\s*IDodoRequest\b','',t)
    t=re.sub(r'\[JsonProperty\("([^"]+)"\)\]',r'[JsonPropertyName("\1")]',t)
    # Helpers de MVC (FileResult) no forman parte del contrato JSON: se omiten.
    i=t.find('public static class FileResultExtensions')
    if i>=0:
        t=t[:t.rfind('\n',0,i)].rstrip()+'\n}\n'
    t=re.sub(r'namespace [\w\.]+\s*\{', 'namespace '+ns+'\n{',t,count=1)
    hdr='// <auto-generated-copy>\n// Copiado de GA2 ('+os.path.relpath(path,str(root))+') para conservar el contrato exacto.\n// Sólo se cambió el namespace y se quitaron dependencias de GA2. No editar a mano: regenerar con tools/copy-ga2-models.py.\n// </auto-generated-copy>\n#nullable enable\n#pragma warning disable CS8618 // Las propiedades no anulables se inicializan por deserialización, igual que en GA2.\n'
    if 'JsonPropertyName' in t: hdr+='using System.Text.Json.Serialization;\n'
    os.makedirs(os.path.dirname(outpath),exist_ok=True)
    open(outpath,'w',encoding='utf-8').write(hdr+'\n'+t.strip()+'\n')
ns='MockIntegrations.Api.Providers.Dodo.Models'
for f in ['DodoDataField','DodoFileItem','DodoFileOperationResponse','DodoFileProperty','DodoFilterParameters','DodoHeader']:
    conv(f'{src}/Dodo/Common/{f}.cs',ns,f'{dst}/Dodo/Models/Common/{f}.cs')
for d in ['Field','File','Forms','Lists','Notification','Offices','Token','User','Workflow']:
    for f in os.listdir(f'{src}/Dodo/{d}/Models'):
        conv(f'{src}/Dodo/{d}/Models/{f}',ns,f'{dst}/Dodo/Models/{f}')
ns2='MockIntegrations.Api.Providers.TusDatos.Models'
for f in os.listdir(f'{src}/TusDatos/Models'):
    conv(f'{src}/TusDatos/Models/{f}',ns2,f'{dst}/TusDatos/Models/{f.replace(" ","")}')
